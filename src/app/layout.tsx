import type { Metadata } from "next";
// dynamic import removed; using ClientShell client wrapper instead
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { ClientShell } from "@/components";
import { headers } from "next/headers";
import { auth } from "@/lib/auth";
import Link from "next/link";
import Image from "next/image";
import SignOutButton from "@/components/SignOutButton";
import DetailsMenu from "@/components/DetailsMenu";
import MovieSearch from "@/components/MovieSearch";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Sign-out behavior is provided by the client component `SignOutButton` to
// avoid calling client-only APIs from server components. See
// `src/components/SignOutButton.tsx` for the implementation.

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const rawHeaders = await headers();
  // Some TypeScript lib targets don't expose entries() on ReadonlyHeaders; declare a small interface
  interface ReadonlyHeadersWithEntries {
    entries?: () => IterableIterator<[string, string]>;
    forEach?: (cb: (value: string, key: string) => void) => void;
  }
  const typedHeaders = rawHeaders as unknown as ReadonlyHeadersWithEntries;
  const headerObj = Object.fromEntries(typedHeaders.entries?.() ?? []);
  const session = await auth.api.getSession({
    headers: headerObj as unknown as Headers,
  });

  return (
    <html lang="en" className={`${geistSans.variable} ${geistMono.variable}`}>
      <body className="font-sans min-h-screen flex flex-col bg-gradient-to-b from-gray-950 via-gray-900 to-gray-950 text-gray-100">
        <ClientShell serverSession={session}>
          {/* Top navigation - compact, inline, modern */}
          <header className="sticky top-0 z-50 backdrop-blur-sm bg-black/40 border-b border-gray-800">
            <div className="max-w-7xl mx-auto flex items-center gap-4 px-4 py-3">
              <Link href="/" className="flex items-center gap-3">
                <span className="tracking-tight font-semibold bg-clip-text text-transparent bg-gradient-to-r from-indigo-400 to-pink-400">
                  MovieShop
                </span>
              </Link>

              <nav
                className="hidden sm:flex items-center gap-4 ml-6 text-sm"
                role="navigation"
                aria-label="Main navigation"
              >
                <Link
                  href="/movies"
                  className="px-3 py-1 rounded-md hover:bg-white/5 transition-colors duration-150"
                >
                  Browse
                </Link>

                <div className="relative">
                  {/* Use a small client DetailsMenu to auto-close on pointer leave and on option click */}
                  <DetailsMenu
                    className="group"
                    summary={
                      <summary className="flex items-center gap-2 px-3 py-1 rounded-md hover:bg-white/5 transition-colors duration-150 cursor-pointer list-none">
                        <span>Collections</span>
                        <svg
                          className="w-3 h-3 opacity-80 transition-transform duration-150 group-open:rotate-180"
                          viewBox="0 0 20 20"
                          fill="none"
                          stroke="currentColor"
                        >
                          <path
                            strokeWidth="1.5"
                            strokeLinecap="round"
                            strokeLinejoin="round"
                            d="M6 8l4 4 4-4"
                          />
                        </svg>
                      </summary>
                    }
                  >
                    <div className="absolute right-0 mt-2 w-48 bg-gray-900/95 border border-gray-800 rounded-lg shadow-lg py-1 z-50 ring-1 ring-black/20">
                      <Link
                        href="/collections/new"
                        className="block px-4 py-2 text-sm hover:bg-white/5 transition-colors duration-150"
                      >
                        New releases
                      </Link>
                      <Link
                        href="/collections/top-rated"
                        className="block px-4 py-2 text-sm hover:bg-white/5 transition-colors duration-150"
                      >
                        Top rated
                      </Link>
                      <Link
                        href="/collections/genres"
                        className="block px-4 py-2 text-sm hover:bg-white/5 transition-colors duration-150"
                      >
                        By genre
                      </Link>
                    </div>
                  </DetailsMenu>
                </div>

                <Link
                  href="/about"
                  className="px-3 py-1 rounded-md hover:bg-white/5 transition-colors duration-150"
                >
                  About
                </Link>
              </nav>

              {/* Inline search using MovieSearch component */}
              <div className="flex-1 flex justify-center">
                <div className="w-full max-w-xl">
                  <MovieSearch
                    initialQuery=""
                    selectedGenre=""
                    autoNavigateOnEmpty={false}
                  />
                </div>
              </div>

              {/* Account / CTA */}
              <div className="ml-auto flex items-center gap-3">
                <a
                  href="/cart"
                  className="inline-flex items-center gap-2 px-3 py-1 rounded-md bg-white/5 hover:bg-white/6 text-sm"
                >
                  <svg
                    className="w-4 h-4"
                    fill="none"
                    stroke="currentColor"
                    viewBox="0 0 24 24"
                  >
                    <path
                      strokeWidth="2"
                      strokeLinecap="round"
                      strokeLinejoin="round"
                      d="M3 3h2l.4 2M7 13h10l4-8H5.4M7 13L5.4 5M7 13l-2 7h14l-2-7M10 21a1 1 0 11-2 0 1 1 0 012 0zm8 0a1 1 0 11-2 0 1 1 0 012 0z"
                    />
                  </svg>
                  <span className="hidden sm:inline">Cart</span>
                </a>

                {session ? (
                  <div className="relative">
                    <DetailsMenu
                      className="group"
                      summary={
                        <summary className="flex items-center gap-2 px-3 py-1 rounded-full bg-white/6 hover:bg-white/8 text-sm cursor-pointer list-none">
                          <div className="w-8 h-8 rounded-full bg-gradient-to-br from-emerald-400 to-teal-500 flex items-center justify-center text-xs font-medium text-black overflow-hidden">
                            {session.user?.image ? (
                              <Image
                                src={session.user.image}
                                alt="avatar"
                                width={32}
                                height={32}
                                className="w-8 h-8 rounded-full object-cover"
                              />
                            ) : (
                              <span>
                                {(session.user?.name || "U").charAt(0)}
                              </span>
                            )}
                          </div>
                          <span className="hidden sm:inline truncate max-w-[8rem]">
                            {session.user?.name ?? "Account"}
                          </span>

                          <svg
                            className="w-3 h-3 opacity-80 transition-transform duration-150 group-open:rotate-180"
                            viewBox="0 0 20 20"
                            fill="none"
                            stroke="currentColor"
                          >
                            <path
                              strokeWidth="1.5"
                              strokeLinecap="round"
                              strokeLinejoin="round"
                              d="M6 8l4 4 4-4"
                            />
                          </svg>
                        </summary>
                      }
                    >
                      <div className="absolute right-0 mt-2 w-48 bg-gray-900/95 border border-gray-800 rounded-lg shadow-lg py-1 z-50 ring-1 ring-black/20">
                        <Link
                          href="/profile"
                          className="block px-4 py-2 text-sm hover:bg-white/5 transition-colors duration-150"
                        >
                          View profile
                        </Link>

                        <SignOutButton />
                      </div>
                    </DetailsMenu>
                  </div>
                ) : (
                  <a
                    href="/sign-in"
                    className="text-sm px-3 py-1 rounded-md bg-indigo-600 hover:bg-indigo-500 text-white"
                  >
                    Sign in
                  </a>
                )}
              </div>
            </div>
          </header>

          {/* Main content centered with modern card-like container */}
          <main className="flex-1">
            <div className="max-w-7xl mx-auto px-4 py-8">
              <div className="bg-gradient-to-br from-gray-900/60 to-gray-900/40 border border-gray-800 rounded-2xl shadow-lg p-6 min-h-[60vh]">
                {children}
              </div>
            </div>
          </main>

          {/* Compact inline footer */}
          <footer className="w-full border-t border-gray-800 bg-black/40">
            <div className="max-w-7xl mx-auto px-4 py-4 flex items-center gap-4 text-sm text-gray-400">
              <div className="flex items-center gap-2">
                <span>© {new Date().getFullYear()}</span>
                <span className="font-semibold bg-clip-text text-transparent bg-gradient-to-r from-indigo-400 to-pink-400">
                  MovieShop
                </span>
                <span className="hidden sm:inline">— Lexicon AB</span>
              </div>

              <p className="mx-auto text-center truncate max-w-lg">
                A demo storefront using Next.js App Router, Prisma, Tailwind and
                Better Auth.
              </p>

              <nav className="ml-auto flex items-center gap-3">
                <a href="/privacy" className="hover:underline">
                  Privacy
                </a>
                <a href="/contact" className="hover:underline">
                  Contact
                </a>
              </nav>
            </div>
          </footer>

          {/* Floating quick-action (accessible, unobtrusive) */}
          <a
            href="/cart"
            aria-label="Open cart"
            className="fixed right-4 bottom-6 z-40 inline-flex items-center gap-2 px-4 py-3 rounded-full bg-indigo-600 hover:bg-indigo-500 text-white shadow-lg focus:outline-none focus:ring-2 focus:ring-indigo-400"
          >
            <svg
              className="w-4 h-4"
              fill="none"
              stroke="currentColor"
              viewBox="0 0 24 24"
            >
              <path
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
                d="M3 3h2l.4 2M7 13h10l4-8H5.4M7 13L5.4 5M7 13l-2 7h14l-2-7"
              />
            </svg>
            <span className="hidden sm:inline">Cart</span>
          </a>
        </ClientShell>
      </body>
    </html>
  );
}
